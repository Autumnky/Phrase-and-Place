const FILE = new URL('../src/data/movies.json', import.meta.url)
const movies = JSON.parse(await readFile(FILE, 'utf8'))
const missing = []
let added = 0

for (const m of movies) {
  const th = TH[m.theme]
  if (th) { m.themeTh = th; added++ }
  else missing.push(`${m.id} "${m.theme}"`)
}

await writeFile(FILE, JSON.stringify(movies, null, 2))
console.log(`เติม themeTh แล้ว ${added} เรื่อง`)
if (missing.length) console.log('\nยังไม่มีท่อนท้าย (ข้ามไว้):\n' + missing.join('\n'))